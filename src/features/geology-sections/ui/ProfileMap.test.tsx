import { cleanup, fireEvent, render, screen } from '@testing-library/react'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { initialSections } from '../../../entities/geology-section/model/fixtures'
import { referenceWellSources } from '../../../entities/geology-section/model/referenceSources'
import { pointAtDepth } from '../../../entities/geology-section/lib/profile'
import { ProfileMap } from './ProfileMap'

const originalMatrix = Object.getOwnPropertyDescriptor(SVGSVGElement.prototype, 'getScreenCTM')
beforeEach(() => {
  vi.stubGlobal('PointerEvent', MouseEvent)
  vi.stubGlobal('DOMPoint', class { constructor(public x: number, public y: number) {} matrixTransform() { return this } })
  Object.defineProperty(SVGSVGElement.prototype, 'getScreenCTM', { configurable: true, value: () => ({ inverse: () => ({ a: 1, b: 0, c: 0, d: 1 }) }) })
})
afterEach(() => {
  cleanup(); vi.unstubAllGlobals()
  if (originalMatrix) Object.defineProperty(SVGSVGElement.prototype, 'getScreenCTM', originalMatrix)
  else Reflect.deleteProperty(SVGSVGElement.prototype, 'getScreenCTM')
})
const point = (x: number, y: number) => {
  const map = screen.getByRole('group', { name: 'Карта скважин и направленного профиля' })
  fireEvent.pointerDown(map, { button: 0, clientX: x, clientY: -y })
  fireEvent.pointerUp(map, { button: 0 })
}
describe('profile map gestures', () => {
  it('centers the reference extent and keeps coordinate labels within the camera while panning and zooming', () => {
    const section = { ...initialSections()[0]!, demoPreset: 'video-reference-v1' as const, profile: [{ x: 0, y: 0 }, { x: 350, y: 0 }] }, change = vi.fn()
    const { container } = render(<ProfileMap section={section} disabled onChange={change} onPending={vi.fn()} />)
    const map = screen.getByRole('group', { name: 'Карта скважин и направленного профиля' })
    const box = () => map.getAttribute('viewBox')!.split(' ').map(Number) as [number, number, number, number]
    const extent = [...section.profile, ...referenceWellSources.flatMap(w => [w.collar, pointAtDepth(w, w.depth)])], before = box()
    expect(before[0] + before[2] / 2).toBeCloseTo((Math.min(...extent.map(p => p.x)) + Math.max(...extent.map(p => p.x))) / 2)
    expect(before[1] + before[3] / 2).toBeCloseTo(-(Math.min(...extent.map(p => p.y)) + Math.max(...extent.map(p => p.y))) / 2)
    const labels = () => [...container.querySelectorAll<SVGTextElement>('[data-map-axes] text')]
    const checkLabels = () => {
      const [x, y, width, height] = box()
      expect(labels().length).toBeGreaterThan(5)
      for (const label of labels()) {
        expect(Number(label.getAttribute('x'))).toBeGreaterThan(x)
        expect(Number(label.getAttribute('x'))).toBeLessThan(x + width)
        expect(Number(label.getAttribute('y'))).toBeGreaterThan(y)
        expect(Number(label.getAttribute('y'))).toBeLessThan(y + height)
      }
      const fontSize = Number(container.querySelector('[data-map-axes]')!.getAttribute('font-size'))
      expect(fontSize * Math.min(1000 / width, 500 / height)).toBeCloseTo(11)
    }
    checkLabels()
    fireEvent.keyDown(map, { key: 'ArrowRight' }); checkLabels()
    expect(box()[0]).toBeCloseTo(before[0] + 20)
    fireEvent.wheel(map, { deltaY: -100, clientX: 100, clientY: 100 }); checkLabels()
    expect(box()[2]).toBeLessThan(before[2])
    fireEvent.click(screen.getByRole('button', { name: 'Весь профиль' }))
    expect(box()).toEqual(before); expect(change).not.toHaveBeenCalled()
  })

  it('retains the original map frame and omits coordinate labels for existing non-reference documents', () => {
    const { container } = render(<ProfileMap section={initialSections()[0]!} disabled onChange={vi.fn()} onPending={vi.fn()} />)
    expect(container.querySelector('[data-map-axes]')).not.toBeInTheDocument()
    expect(screen.getByRole('group', { name: 'Карта скважин и направленного профиля' }).getAttribute('viewBox')).toBe('-30 -230 550 250')
  })
  it('pans in viewing mode without modifying the profile or adding wells', () => {
    const change = vi.fn()
    render(<ProfileMap section={initialSections()[0]!} disabled={true} onChange={change} onPending={vi.fn()} />)
    const map = screen.getByRole('group', { name: 'Карта скважин и направленного профиля' })
    const before = map.getAttribute('viewBox')!.split(' ').map(Number)
    fireEvent.pointerDown(map, { button: 0, clientX: 100, clientY: 100 })
    fireEvent.pointerMove(map, { clientX: 160, clientY: 120 }); fireEvent.pointerUp(map)
    const after = map.getAttribute('viewBox')!.split(' ').map(Number)
    expect(after[0]).toBeCloseTo(before[0]! - 60)
    expect(after[1]).toBeCloseTo(before[1]! - 20)
    expect(change).not.toHaveBeenCalled()
  })
  it('zooms with the wheel and does not add a well on right click', () => {
    const change = vi.fn()
    render(<ProfileMap section={initialSections()[0]!} disabled={false} onChange={change} onPending={vi.fn()} />)
    const map = screen.getByRole('group', { name: 'Карта скважин и направленного профиля' })
    const before = map.getAttribute('viewBox')!.split(' ').map(Number)
    fireEvent.wheel(map, { deltaY: -100, clientX: 100, clientY: 100 })
    const after = map.getAttribute('viewBox')!.split(' ').map(Number)
    expect(after[2]).toBeLessThan(before[2]!)
    fireEvent.click(screen.getByRole('button', { name: 'Добавить скважины' }))
    fireEvent.pointerDown(screen.getByRole('button', { name: 'Добавить ГС-107 в разрез' }), { button: 2 })
    expect(change).not.toHaveBeenCalled()
  })
  it('previews and joins an independent segment, validates coordinates and cancels atomically', () => {
    const section = initialSections()[0]!, change = vi.fn(), pending = vi.fn()
    render(<ProfileMap section={section} disabled={false} onChange={change} onPending={pending} />)
    fireEvent.click(screen.getByRole('button', { name: 'Независимый сегмент' }))
    fireEvent.click(screen.getByRole('button', { name: 'Задать координатами' }))
    expect(pending).toHaveBeenLastCalledWith(true); expect(change).not.toHaveBeenCalled()
    expect(screen.getByRole('dialog', { name: 'Соединить независимый сегмент' })).toBeInTheDocument()
    fireEvent.change(screen.getByLabelText('Сегмент 2, X'), { target: { value: '' } })
    expect(screen.getByRole('button', { name: 'Соединить сегмент' })).toBeDisabled()
    fireEvent.change(screen.getByLabelText('Сегмент 2, X'), { target: { value: '550' } })
    fireEvent.click(screen.getByRole('button', { name: 'Соединить сегмент' }))
    expect(change).toHaveBeenCalledTimes(1)
    expect(change.mock.calls[0]![0].profile).toHaveLength(4)
    expect(change.mock.calls[0]![0].wellIds).toEqual(section.wellIds)
    expect(pending).toHaveBeenLastCalledWith(false)
    fireEvent.click(screen.getByRole('button', { name: 'Независимый сегмент' })); point(490, 150)
    fireEvent.keyDown(screen.getByRole('group', { name: 'Карта скважин и направленного профиля' }), { key: 'Escape' })
    expect(change).toHaveBeenCalledTimes(1); expect(pending).toHaveBeenLastCalledWith(false)
  })
  it('previews two points before replacing the profile and preserves the well composition', () => {
    const section = initialSections()[0]!, change = vi.fn(), pending = vi.fn()
    render(<ProfileMap section={section} disabled={false} onChange={change} onPending={pending} />)
    fireEvent.click(screen.getByRole('button', { name: 'Новый профиль' }))
    point(0, 30)
    expect(pending).toHaveBeenLastCalledWith(true)
    expect(change).not.toHaveBeenCalled()
    point(470, 125)
    expect(screen.getByRole('dialog', { name: 'Новый профиль на карте' })).toBeInTheDocument()
    expect(change).not.toHaveBeenCalled()
    fireEvent.click(screen.getByRole('button', { name: 'Применить профиль' }))
    expect(change.mock.calls[0]![0]).toMatchObject({ profile: [{ x: 0, y: 30 }, { x: 470, y: 125 }], wellIds: section.wellIds })
    expect(pending).toHaveBeenLastCalledWith(false)
  })
  it('cancels a partial gesture with Escape and rejects a zero-length candidate', () => {
    const section = initialSections()[0]!, change = vi.fn(), pending = vi.fn()
    render(<ProfileMap section={section} disabled={false} onChange={change} onPending={pending} />)
    fireEvent.click(screen.getByRole('button', { name: 'Новый профиль' })); point(0, 30)
    fireEvent.keyDown(screen.getByRole('group', { name: 'Карта скважин и направленного профиля' }), { key: 'Escape' })
    expect(pending).toHaveBeenLastCalledWith(false)
    fireEvent.click(screen.getByRole('button', { name: 'Новый профиль' })); point(0, 30); point(0, 30)
    expect(screen.getByRole('button', { name: 'Применить профиль' })).toBeDisabled()
    expect(screen.getByRole('alert')).toHaveTextContent('Нулевой сегмент')
    fireEvent.click(screen.getByRole('button', { name: 'Отмена' }))
    expect(change).not.toHaveBeenCalled()
    expect(pending).toHaveBeenLastCalledWith(false)
  })
  it('blocks shortening a profile past a dependent manual region', () => {
    const section = initialSections()[0]!, change = vi.fn()
    section.graphics = [{ id: 'l', type: 'lithology', name: 'Пласт', rock: 'sand', closed: true, reversed: false, smooth: false, points: [{ x: 100, z: 0 }, { x: 200, z: 0 }, { x: 150, z: -10 }] }]
    render(<ProfileMap section={section} disabled={false} onChange={change} onPending={vi.fn()} />)
    fireEvent.click(screen.getByRole('button', { name: 'Новый профиль' })); point(0, 30); point(10, 30)
    expect(screen.getByRole('alert')).toHaveTextContent('Пласт')
    expect(screen.getByRole('button', { name: 'Применить профиль' })).toBeDisabled()
    expect(change).not.toHaveBeenCalled()
  })
  it('adds wells with keyboard without changing the profile or layer participation and respects read-only', () => {
    const section = initialSections()[0]!, change = vi.fn()
    const view = render(<ProfileMap section={section} disabled={false} onChange={change} onPending={vi.fn()} />)
    fireEvent.click(screen.getByRole('button', { name: 'Добавить скважины' }))
    fireEvent.keyDown(screen.getByRole('button', { name: 'Добавить ГС-107 в разрез' }), { key: 'Enter' })
    const next = change.mock.calls[0]![0]
    expect(next.wellIds).toEqual([...section.wellIds, 'GTR-W7'])
    expect(next.profile).toEqual(section.profile)
    expect(next.participation).toEqual(section.participation)
    view.rerender(<ProfileMap section={next} disabled={false} onChange={change} onPending={vi.fn()} />)
    fireEvent.keyDown(screen.getByRole('button', { name: 'Добавить ГС-107 в разрез' }), { key: ' ' })
    expect(change).toHaveBeenCalledTimes(1)
    view.rerender(<ProfileMap section={next} disabled onChange={change} onPending={vi.fn()} />)
    expect(screen.getByRole('button', { name: 'Новый профиль' })).toBeDisabled()
    fireEvent.keyDown(screen.getByRole('button', { name: 'Добавить ГС-106 в разрез' }), { key: 'Enter' })
    expect(change).toHaveBeenCalledTimes(1)
  })
})
