import { cleanup, fireEvent, render, screen, within } from '@testing-library/react'
import { afterEach, describe, expect, it } from 'vitest'
import { IntervalReview } from './IntervalReview'

afterEach(() => { cleanup(); localStorage.clear() })
describe('AP interval workflow', () => {
  it('validates bounds and persists the selected horizon per well', () => {
    const view = render(<IntervalReview wellId="test-ap" depth={500} canEdit />)
    fireEvent.click(screen.getByRole('button', { name: 'Параметры' }))
    fireEvent.change(screen.getByLabelText('Горизонт'), { target: { value: 'K₂ новый' } })
    fireEvent.change(screen.getByLabelText('До, м'), { target: { value: '999' } })
    fireEvent.click(screen.getByRole('button', { name: 'Применить' }))
    expect(screen.getByRole('alert')).toHaveTextContent('Проверьте границы')
    fireEvent.change(screen.getByLabelText('До, м'), { target: { value: '350' } })
    fireEvent.change(screen.getByLabelText('До горизонта, м'), { target: { value: '350' } })
    fireEvent.click(screen.getByRole('button', { name: 'Применить' }))
    fireEvent.click(screen.getByRole('button', { name: 'Сохранить интервалы' }))
    view.unmount()
    render(<IntervalReview wellId="test-ap" depth={500} canEdit />)
    fireEvent.click(screen.getByRole('button', { name: 'Параметры' }))
    expect(screen.getByLabelText('Горизонт')).toHaveValue('K₂ новый')
  })
  it('selects an interval from any cell in its row and from the keyboard', () => {
    render(<IntervalReview wellId="select-ap" depth={500} canEdit />)
    const rows = within(screen.getByRole('table', { name: 'Аномальные пересечения' })).getAllByRole('row')
    fireEvent.click(rows[2]!.querySelectorAll('td')[2]!)
    expect(rows[2]).toHaveAttribute('aria-current', 'true')
    fireEvent.keyDown(rows[3]!, { key: 'Enter' })
    expect(rows[3]).toHaveAttribute('aria-current', 'true')
  })
  it('keeps productive horizons inside their crossing and changes the displayed horizon on selection', () => {
    render(<IntervalReview wellId="horizon-ap" depth={500} canEdit />)
    fireEvent.click(screen.getByRole('button', { name: 'Свойства' }))
    fireEvent.change(screen.getByLabelText('Горизонт'), { target: { value: 'Горизонт первого АП' } })
    fireEvent.change(screen.getByLabelText('Кф, м/сут', { exact: true }), { target: { value: '11.2' } })
    fireEvent.click(screen.getByRole('button', { name: 'Применить' }))
    const table = screen.getByRole('table', { name: 'Продуктивные горизонты' })
    expect(within(table).getByText('Горизонт первого АП')).toBeInTheDocument()
    const apRows = within(screen.getByRole('table', { name: 'Аномальные пересечения' })).getAllByRole('row')
    fireEvent.click(apRows[2]!)
    expect(within(table).queryByText('Горизонт первого АП')).not.toBeInTheDocument()
    fireEvent.click(apRows[1]!)
    expect(within(table).getByText('11,2')).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'Свойства' }))
    fireEvent.change(screen.getByLabelText('До, м'), { target: { value: '499' } })
    fireEvent.click(screen.getByRole('button', { name: 'Применить' }))
    expect(screen.getByRole('alert')).toHaveTextContent('внутри выбранного пересечения')
  })
  it('zooms to a crossing and toggles curves without changing the data', () => {
    render(<IntervalReview wellId="chart-ap" depth={500} canEdit />)
    fireEvent.click(screen.getByRole('button', { name: 'К пересечению' }))
    const chart = screen.getByRole('region', { name: 'Совмещённые диаграммы каротажа' })
    expect(within(chart).queryByText('Глубина 0–500 м')).not.toBeInTheDocument()
    const sp = within(chart).getByRole('button', { name: 'Кривая ПС' })
    fireEvent.click(sp)
    expect(sp).toHaveAttribute('aria-pressed', 'false')
    fireEvent.click(screen.getByRole('button', { name: 'Вся глубина' }))
    expect(within(chart).getByText('Глубина 0–500 м')).toBeInTheDocument()
    expect(screen.getByRole('button', { name: 'Сохранить интервалы' })).toBeDisabled()
  })
  it('allows viewing but prevents changes without edit permission', () => {
    render(<IntervalReview wellId="readonly-ap" depth={500} canEdit={false} />)
    expect(screen.getByRole('button', { name: 'Импорт GIK' })).toBeDisabled()
    expect(screen.getByRole('button', { name: 'Добавить пересечение' })).toBeDisabled()
    fireEvent.click(screen.getByRole('button', { name: 'Параметры' }))
    expect(screen.getByLabelText('Горизонт')).toBeDisabled()
    expect(screen.queryByRole('button', { name: 'Применить' })).not.toBeInTheDocument()
  })
})
