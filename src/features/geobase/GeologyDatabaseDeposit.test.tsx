import { QueryClient, QueryClientProvider } from '@tanstack/react-query'
import { act, cleanup, fireEvent, render, screen, waitFor, within } from '@testing-library/react'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { setUiLocale } from '../../shared/lib/useUiLocale'
import { defaultPersona } from '../../entities/session/model/personas'
import { SessionContext } from '../../entities/session/model/sessionContext'
import * as api from '../../repository/api'
import { demoDatabase } from '../../repository/demo/demoDatabase'
import { GeologyDatabaseDeposit } from './GeologyDatabaseDeposit'

const onOpenDeposit = vi.fn()

function mount(depositId = 'DEP-SARYTAU', readOnly = false, admin = false, view: 'overview' | 'conditions' = 'conditions') {
  const client = new QueryClient({ defaultOptions: { queries: { retry: false } } })
  const persona = admin ? { ...defaultPersona, roles: ['R13' as const] } : readOnly ? { ...defaultPersona, roles: ['R3' as const] } : defaultPersona
  return render(<QueryClientProvider client={client}><SessionContext.Provider value={{ status: 'authenticated', persona, signIn: () => persona, signOut: vi.fn(), switchPersona: vi.fn() }}>
    <GeologyDatabaseDeposit depositId={depositId} view={view} onOpenDeposit={onOpenDeposit} onDeleted={vi.fn()} />
  </SessionContext.Provider></QueryClientProvider>)
}

describe('Deposit condition limits', () => {
  beforeEach(async () => { localStorage.removeItem('kapgeo.ui.locale'); vi.stubGlobal('ResizeObserver', class { observe() {} disconnect() {} }); vi.spyOn(HTMLCanvasElement.prototype, 'getContext').mockImplementation(() => null); onOpenDeposit.mockReset(); await demoDatabase.reset() })
  afterEach(async () => { cleanup(); vi.restoreAllMocks(); vi.unstubAllGlobals(); await demoDatabase.reset() })

  it('opens one editable deposit set, saves and closes, then reloads without approval or versions', async () => {
    const confirm = vi.spyOn(window, 'confirm')
    const view = mount('DEP-SARYTAU', false, false, 'conditions')
    const open = await screen.findByRole('button', { name: 'Изменить' })
    expect(screen.getAllByRole('button', { name: 'Изменить' })).toHaveLength(1)
    open.focus()
    fireEvent.click(open)
    const dialog = screen.getByRole('dialog', { name: 'Кондиционные лимиты Сарытау' })
    const required = within(dialog).getByRole('group', { name: 'Обязательные' })
    const optional = within(dialog).getByRole('group', { name: 'Необязательные' })
    expect(within(dialog).getAllByRole('group')).toEqual([required, optional])
    expect(required.querySelectorAll('input[required]')).toHaveLength(9)
    expect(optional.querySelectorAll('input')).toHaveLength(25)
    expect(optional.querySelectorAll('input[required]')).toHaveLength(0)
    expect(within(required).getByRole('combobox', { name: /категории С₂/ })).toHaveValue('Без ограничения')
    expect(within(dialog).getAllByRole('button').map((button) => button.textContent)).toEqual(['Сохранить', 'Отменить'])
    const cutoff = within(dialog).getByLabelText('Бортовое содержание урана')
    expect(cutoff).toBeEnabled()
    expect(cutoff).toHaveFocus()
    fireEvent.change(cutoff, { target: { value: '' } })
    expect(within(dialog).getByRole('button', { name: 'Сохранить' })).toBeDisabled()
    fireEvent.change(cutoff, { target: { value: '0.025' } })
    const sectionTop = within(optional).getByLabelText('Верхняя высота разрезов по умолчанию')
    expect(sectionTop).toHaveValue('-420')
    fireEvent.change(sectionTop, { target: { value: '' } })
    expect(within(dialog).getByRole('button', { name: 'Сохранить' })).toBeEnabled()
    fireEvent.click(within(dialog).getByRole('button', { name: 'Сохранить' }))
    await waitFor(() => expect(screen.queryByRole('dialog')).not.toBeInTheDocument())
    expect(open).toHaveFocus()
    expect(confirm).not.toHaveBeenCalled()
    view.unmount()
    mount('DEP-SARYTAU', false, false, 'conditions')
    fireEvent.click(await screen.findByRole('button', { name: 'Изменить' }))
    expect(screen.getByLabelText('Бортовое содержание урана')).toHaveValue('0.025')
    expect(screen.getByLabelText('Бортовое содержание урана')).toBeEnabled()
    expect(screen.getByLabelText('Верхняя высота разрезов по умолчанию')).toHaveValue('')
    expect((await api.fetchGeologicalMasterData()).conditionSets.filter((item) => item.depositId === 'DEP-SARYTAU')).toHaveLength(1)
  })

  it('asks before discarding edits and restores stored values on reopening', async () => {
    mount('DEP-SARYTAU', false, false, 'conditions')
    fireEvent.click(await screen.findByRole('button', { name: 'Изменить' }))
    fireEvent.change(screen.getByLabelText('Бортовое содержание урана'), { target: { value: 'discard me' } })
    fireEvent.click(screen.getByRole('button', { name: 'Отменить' }))
    expect(screen.getByRole('dialog', { name: 'Есть несохранённые изменения' })).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'Отменить изменения и закрыть' }))
    fireEvent.click(screen.getByRole('button', { name: 'Изменить' }))
    expect(screen.getByLabelText('Бортовое содержание урана')).toHaveValue('0,01')
    fireEvent.keyDown(screen.getByRole('dialog'), { key: 'Escape' })
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
  })

  it('allows a deposit without sites to save its first and only set', async () => {
    mount('DEP-SEVERNOE', false, true, 'conditions')
    fireEvent.click(await screen.findByRole('button', { name: 'Изменить' }))
    expect(screen.getByRole('dialog', { name: 'Кондиционные лимиты Северное' })).toBeInTheDocument()
    fireEvent.change(screen.getByLabelText('Бортовое содержание урана'), { target: { value: '0.02' } })
    fireEvent.click(screen.getByRole('button', { name: 'Сохранить' }))
    await waitFor(() => expect(screen.queryByRole('dialog')).not.toBeInTheDocument())
    fireEvent.click(screen.getByRole('button', { name: 'Изменить' }))
    expect(screen.getByLabelText('Бортовое содержание урана')).toHaveValue('0.02')
    expect((await api.fetchGeologicalMasterData()).conditionSets.filter((item) => item.depositId === 'DEP-SEVERNOE')).toHaveLength(1)
  })

  it('preserves edits and shows the save error inside the open form', async () => {
    vi.spyOn(api, 'saveConditionSet').mockRejectedValueOnce(new Error('Не удалось сохранить лимиты.'))
    mount('DEP-SARYTAU', false, false, 'conditions')
    fireEvent.click(await screen.findByRole('button', { name: 'Изменить' }))
    fireEvent.change(screen.getByLabelText('Бортовое содержание урана'), { target: { value: '0.03' } })
    fireEvent.click(screen.getByRole('button', { name: 'Сохранить' }))
    const dialog = screen.getByRole('dialog')
    expect(await within(dialog).findByRole('alert')).toHaveTextContent('Не удалось сохранить лимиты.')
    expect(screen.getByLabelText('Бортовое содержание урана')).toHaveValue('0.03')
    expect(screen.getByRole('button', { name: 'Сохранить' })).toBeEnabled()
  })

  it('keeps the form read-only without an edit permission', async () => {
    mount('DEP-SARYTAU', true, false, 'conditions')
    fireEvent.click(await screen.findByRole('button', { name: 'Изменить' }))
    expect(screen.getByLabelText('Бортовое содержание урана')).toBeDisabled()
    expect(screen.getByRole('button', { name: 'Сохранить' })).toBeDisabled()
    expect(screen.getByRole('button', { name: 'Отменить' })).toBeEnabled()
  })

  it('shows sites and ore deposits in one structure table with type badges', async () => {
    mount()
    expect(await screen.findByRole('heading', { name: 'Основные сведения' })).toBeVisible()
    expect(screen.getByText('Урановое месторождение Сарытау.')).toBeVisible()
    expect(screen.queryByText('Sarytau uranium deposit.')).not.toBeInTheDocument()
    expect(screen.getByRole('heading', { name: 'Кондиционные лимиты Сарытау' })).toBeVisible()
    const [required, optional] = document.querySelectorAll('.geobase-condition-values')
    expect(required?.previousElementSibling).toHaveTextContent('Обязательные')
    expect(required?.querySelectorAll('dt')).toHaveLength(9)
    expect(optional?.previousElementSibling).toHaveTextContent('Необязательные')
    expect(optional?.querySelectorAll('dt')).toHaveLength(25)
    expect(screen.queryByRole('heading', { name: 'Скважины' })).not.toBeInTheDocument()
    expect(screen.getByText('Описание')).toBeVisible()
    expect(screen.getByRole('button', { name: 'Редактировать' })).toBeVisible()
    expect(screen.getByRole('button', { name: 'Добавить объект' })).toBeVisible()
    const structure = screen.getByRole('table', { name: 'Структура месторождения' })
    expect(screen.getAllByRole('table')).toHaveLength(1)
    expect(within(structure).getAllByRole('row')).toHaveLength(7)
    const siteBadges = within(structure).getAllByText('Участок')
    const oreDepositBadges = within(structure).getAllByText('Рудная залежь')
    expect(siteBadges).toHaveLength(3)
    expect(oreDepositBadges).toHaveLength(3)
    for (const badge of siteBadges) expect(badge).toHaveClass('badge--tag', 'badge--info')
    for (const badge of oreDepositBadges) expect(badge).toHaveClass('badge--tag', 'badge--warning')
    expect(within(structure).getByText('Қарасай')).toBeVisible()
    expect(within(structure).getByText('Karasai')).toBeVisible()
  })
  it('starts with a well-only map and keeps the filters with the coordinate readout', async () => {
    mount('DEP-SARYTAU', false, false, 'overview')
    expect(await screen.findByLabelText('8215 скважин на карте')).toBeInTheDocument()
    expect(screen.queryByRole('heading')).not.toBeInTheDocument()
    expect(screen.queryByRole('button', { name: 'Редактировать' })).not.toBeInTheDocument()
    const coordinates = screen.getByText('X — север · Y — восток · метры')
    const footer = coordinates.closest('.map-canvas-footer')!
    expect(footer).toContainElement(screen.getByRole('combobox', { name: 'Участок' }))
    expect(footer).toContainElement(screen.getByRole('group', { name: 'Типы скважин' }))
    expect(footer).not.toContainElement(screen.getByRole('group', { name: 'Управление картой' }))
    fireEvent.click(screen.getByRole('button', { name: /Наблюдательная/ }), { altKey: true })
    await waitFor(() => expect(document.querySelector('[data-field-wells]')).toHaveAttribute('data-field-wells', '449'))
    const display = screen.getByRole('button', { name: 'Настройки отображения карты' })
    fireEvent.click(display)
    const labels = screen.getByRole('switch', { name: 'Номера на текущем масштабе' })
    expect(labels).toHaveAttribute('aria-checked', 'false')
    fireEvent.click(labels)
    expect(labels).toHaveAttribute('aria-checked', 'true')
    fireEvent.click(screen.getByRole('switch', { name: 'Отображать карту' }))
    expect(document.querySelector('[data-topo-basemap]')).toBeNull()
    fireEvent.click(screen.getByRole('switch', { name: 'Отображать сетку' }))
    expect(document.querySelector('.map-grid')).toBeNull()
    fireEvent.keyDown(document, { key: 'Escape' })
    expect(screen.queryByRole('group', { name: 'Настройки отображения карты' })).not.toBeInTheDocument()
    expect(display).toHaveFocus()
  })

  it('edits deposit data from the header and updates the unified view after saving', async () => {
    mount()
    fireEvent.click(await screen.findByRole('button', { name: 'Редактировать' }))
    const dialog = screen.getByRole('dialog', { name: 'Редактирование месторождения Сарытау' })
    expect(within(dialog).queryByRole('button', { name: 'Добавить объект' })).not.toBeInTheDocument()
    expect(within(dialog).queryByText('Структура месторождения')).not.toBeInTheDocument()
    expect(dialog.querySelector('.panel')).toBeNull()
    fireEvent.change(within(dialog).getByLabelText('Описание (EN)'), { target: { value: 'Updated deposit description.' } })
    fireEvent.click(within(dialog).getByRole('button', { name: 'Сохранить изменения' }))
    await waitFor(() => expect(screen.queryByRole('dialog')).not.toBeInTheDocument())
    act(() => setUiLocale('en'))
    expect(screen.getByText('Updated deposit description.')).toBeVisible()
    expect((await api.fetchGeologicalMasterData()).deposits.find((item) => item.id === 'DEP-SARYTAU')?.descriptionEn).toBe('Updated deposit description.')
    expect((await api.fetchGeologicalMasterData()).deposits.find((item) => item.id === 'DEP-SARYTAU')?.occurrences).toHaveLength(6)
  })

  it('shows the empty structure in a deposit without objects', async () => {
    mount('DEP-SEVERNOE')
    expect(await screen.findByText('Объекты ещё не добавлены.')).toBeVisible()
    expect(screen.queryByRole('table', { name: 'Структура месторождения' })).not.toBeInTheDocument()
  })

  it('manages structure objects through the shared form and keeps values after a duplicate error', async () => {
    mount()
    fireEvent.click(await screen.findByRole('button', { name: 'Добавить объект' }))
    let dialog = screen.getByRole('dialog', { name: 'Добавить объект' })
    expect(within(dialog).getByRole('combobox', { name: 'Тип объекта' })).toHaveValue('Рудная залежь')
    expect(within(dialog).getAllByRole('option').map((option) => option.textContent)).toEqual(expect.arrayContaining(['Рудная залежь', 'Участок', 'Площадь']))
    for (const locale of ['RU', 'KZ', 'EN']) fireEvent.change(within(dialog).getByLabelText(`Название (${locale})`), { target: { value: 'КС-14' } })
    fireEvent.click(within(dialog).getByRole('button', { name: 'Сохранить' }))
    expect(await within(dialog).findByRole('alert')).toHaveTextContent('дубликат')
    expect(within(dialog).getByLabelText('Название (RU)')).toHaveValue('КС-14')
    for (const locale of ['RU', 'KZ', 'EN']) fireEvent.change(within(dialog).getByLabelText(`Название (${locale})`), { target: { value: 'NEW-01' } })
    fireEvent.change(within(dialog).getByRole('combobox', { name: 'Тип объекта' }), { target: { value: 'Участок' } })
    fireEvent.click(within(dialog).getByRole('button', { name: 'Сохранить' }))
    await waitFor(() => expect(screen.queryByRole('dialog')).not.toBeInTheDocument())
    fireEvent.click(screen.getByRole('button', { name: 'Действия: Участок «NEW-01»' }))
    fireEvent.click(screen.getByRole('menuitem', { name: 'Редактировать' }))
    dialog = screen.getByRole('dialog', { name: 'Редактирование объекта' })
    expect(within(dialog).getByRole('combobox', { name: 'Тип объекта' })).toHaveValue('Участок')
    expect(within(dialog).getAllByRole('option').map((option) => option.textContent)).toEqual(expect.arrayContaining(['Рудная залежь', 'Участок', 'Площадь']))
    fireEvent.change(within(dialog).getByRole('combobox', { name: 'Тип объекта' }), { target: { value: 'Рудная залежь' } })
    fireEvent.change(within(dialog).getByLabelText('Название (EN)'), { target: { value: 'New occurrence' } })
    fireEvent.click(within(dialog).getByRole('button', { name: 'Сохранить' }))
    await waitFor(() => expect(screen.queryByRole('dialog')).not.toBeInTheDocument())
    const row = screen.getByRole('row', { name: /NEW-01.*New occurrence/ })
    expect(within(row).getByText('Рудная залежь')).toHaveClass('badge')
    fireEvent.click(within(row).getByRole('button', { name: 'Действия: Рудная залежь «NEW-01»' }))
    fireEvent.click(screen.getByRole('menuitem', { name: 'Удалить' }))
    fireEvent.click(within(screen.getByRole('dialog')).getByRole('button', { name: 'Удалить' }))
    await waitFor(() => expect(screen.queryByRole('dialog')).not.toBeInTheDocument())
    expect(screen.queryByRole('row', { name: /NEW-01/ })).not.toBeInTheDocument()
  })

  it('dismisses row actions with the keyboard and retains used occurrences after a deletion failure', async () => {
    mount()
    const trigger = await screen.findByRole('button', { name: 'Действия: Рудная залежь «КС-14»' })
    fireEvent.keyDown(trigger, { key: 'ArrowDown' })
    fireEvent.keyDown(screen.getByRole('menu'), { key: 'End' })
    expect(screen.getByRole('menuitem', { name: 'Удалить' })).toHaveFocus()
    fireEvent.keyDown(screen.getByRole('menu'), { key: 'Escape' })
    expect(trigger).toHaveFocus()
    expect(screen.queryByRole('menu')).not.toBeInTheDocument()
    fireEvent.click(trigger)
    fireEvent.click(screen.getByRole('menuitem', { name: 'Удалить' }))
    const dialog = screen.getByRole('dialog')
    fireEvent.click(within(dialog).getByRole('button', { name: 'Удалить' }))
    expect(await within(dialog).findByRole('alert')).toHaveTextContent('используется скважинами')
    fireEvent.click(within(dialog).getByRole('button', { name: 'Отменить' }))
    expect(screen.getByRole('button', { name: 'Действия: Рудная залежь «КС-14»' })).toBeInTheDocument()
  })

  it('shows audit in the same view only with permission and omits editing for readers', async () => {
    const view = mount('DEP-SARYTAU', false, true, 'conditions')
    expect(await screen.findByRole('heading', { name: 'Аудит месторождения' })).toBeVisible()
    view.unmount()
    mount('DEP-SARYTAU', true)
    expect(await screen.findByRole('heading', { name: 'Сарытау' })).toBeVisible()
    expect(screen.queryByRole('button', { name: 'Редактировать' })).not.toBeInTheDocument()
    expect(screen.queryByRole('heading', { name: 'Аудит месторождения' })).not.toBeInTheDocument()
    expect(screen.queryByRole('button', { name: /Действия:/ })).not.toBeInTheDocument()
    expect(screen.queryByRole('button', { name: 'Добавить объект' })).not.toBeInTheDocument()
  })
})
